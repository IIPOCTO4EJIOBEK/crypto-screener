"""Издержки сделки: комиссия, проскальзывание и фандинг — в единицах риска R.

Зачем это нужно. Все прогоны в проекте показывают результат в R — в единицах
риска сделки, — и такое число удобно ровно до тех пор, пока издержки не
посчитаны. Но издержки в R зависят от того, насколько далеко стоит стоп:

    издержки(R) = издержки(в % от цены) / расстояние до стопа(в % от цены)

Стоп в 0.3 % от цены и круговая комиссия 0.08 % дают 0.27 R — больше четверти
риска съедают вход и выход, до всякого движения цены. У сделки со стопом в
3 % те же 0.08 % стоят 0.027 R. Поэтому средний R, не очищенный от издержек,
о доходности не говорит ничего: одна и та же стратегия с близкими стопами
выглядит хуже не потому, что хуже угадывает, а потому, что дороже торгует.

Что считается:
  комиссия — за каждую сторону, доля от ноционала (тейкер, вход и выход по
    рынку: скринер не выставляет лимитных заявок и не ждёт исполнения);
  проскальзывание — доля от цены за каждую сторону; по умолчанию 1 б.п.,
    что для ликвидных пар на 1m-15m осторожно, а для мелких монет мало;
  фандинг — ставки, начисленные за время удержания позиции. Положительная
    ставка: лонг платит, шорт получает. Свечи в проекте спотовые, а фандинг —
    атрибут перпетуала, поэтому он учитывается как явное допущение о том, что
    позиция держится в перпетуале брокера, и по умолчанию включён отдельным
    флагом, чтобы числа можно было видеть и с ним, и без него.

Чего здесь нет: стаканной проскальзывания по объёму (нужен размер позиции),
задержки сигнала, частичного исполнения. Это следующий слой, и без него
издержки здесь — нижняя оценка, а не точная величина.
"""

from __future__ import annotations

from dataclasses import dataclass

from src.data.archive import FundingRate


@dataclass(frozen=True)
class Costs:
    """Ставки издержек. Значения по умолчанию — для перпетуалов Binance."""

    taker_fee: float = 0.0004      # 0.04 % за сторону, тариф без скидок
    slippage: float = 0.0001       # 1 б.п. за сторону
    funding: bool = True           # учитывать ставки финансирования
    cashback: float = 0.0          # возврат комиссии (у Tiger до 0.45-0.50)

    @property
    def per_side(self) -> float:
        return (self.taker_fee * (1.0 - self.cashback)) + self.slippage

    @property
    def round_trip(self) -> float:
        """Вход и выход вместе, доля от цены, без фандинга."""
        return 2.0 * self.per_side


def funding_between(schedule: list[FundingRate], start_ms: int,
                    end_ms: int) -> float:
    """Сумма ставок, начисленных за время удержания (начисления строго после
    входа и не позже выхода)."""
    total = 0.0
    for event in schedule:
        if start_ms < event.calc_time <= end_ms:
            total += event.last_funding_rate
    return total


def cost_r(entry: float, stop: float, entry_ms: int, exit_ms: int, side: str,
           costs: Costs, schedule: list[FundingRate] | None = None) -> float:
    """Издержки сделки в единицах риска R (то есть в долях расстояния до стопа).

    Возвращает неотрицательную величину: фандинг в пользу позиции уменьшает
    издержки, но не делает их отрицательными — комиссия и проскальзывание
    платятся всегда.
    """
    risk = abs(entry - stop)
    if risk <= 0 or entry <= 0:
        return 0.0
    fraction = costs.round_trip
    if costs.funding and schedule:
        paid = funding_between(schedule, entry_ms, exit_ms)
        if side == "short":
            paid = -paid          # положительная ставка: шорт получает
        fraction += paid
    fraction = max(fraction, 0.0)
    return fraction * entry / risk
