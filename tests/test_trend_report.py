"""Тесты страницы тренд-отчёта: раздел про задержку исполнения.

Проверяется не разметка, а честность текста. Различие с рынком значимо и в
плюс, и в минус, и страница обязана называть направление: строка «значимо»
без него на такой странице читается как «работает». Ровно этот класс ошибки
уже случался в измерении формаций.
"""

from __future__ import annotations

from tools.trend_report import build, lag_table


def _row(lag: int, sharpe: float, market: float, p: float | None,
         significant: bool | None) -> dict:
    return dict(lag=lag, n=480 - lag, exposure=0.47, in_market=0.93,
                turnover=49.5, total=0.5, cagr=0.1, sharpe=sharpe, dd=-0.8,
                market_sharpe=market, market_total=0.6, z=2.0, p=p,
                значимо=significant)


def _payload(rows: list[dict] | None) -> dict:
    p = {"прогоны": {}, "условия": {"символы": ["A"], "первый месяц": "2020-01",
                                    "последний месяц": "2026-08",
                                    "издержки за круг": 0.0012,
                                    "вселенная": "тест"},
         "вердикты": {}}
    if rows is not None:
        p["вердикты"]["задержка"] = dict(правило="L28 H5", строки=rows,
                                         описание="сигнал дня i, вход i+лаг")
    return p


def test_направление_различия_названо_в_таблице():
    out = lag_table([
        _row(1, 0.64, 0.51, 0.0001, True),     # значимо лучше рынка
        _row(5, 0.46, 0.51, 0.0280, True),     # значимо хуже рынка
        _row(3, 0.47, 0.48, 0.4520, False),    # не значимо
    ])
    assert "лучше рынка" in out
    assert "хуже рынка" in out
    assert out.count("хуже рынка") == 1, "минус не должен попасть в плюсовую строку"


def test_значимый_минус_не_показан_как_успех():
    """Ключевая проверка: страница не имеет права сказать «значимо» и молчать
    о том, что значимо оно против правила."""
    page = build(_payload([_row(1, 0.64, 0.51, 0.0001, True),
                           _row(10, 0.36, 0.49, 0.0001, True)]))
    assert "при 10 дн — хуже рынка" in page
    assert "при 1 дн — лучше рынка" in page


def test_без_перебора_задержки_раздела_нет():
    page = build(_payload(None))
    assert "Время жизни сигнала" not in page
    assert "Проверка вне выбора параметров" not in page, \
        "пустой раздел не должен оставлять заголовок"


def test_незначимые_задержки_не_попадают_в_вердикт():
    page = build(_payload([_row(1, 0.50, 0.51, 0.9000, False)]))
    assert "Ни при одной задержке различие с рынком не значимо" in page
